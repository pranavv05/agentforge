// Copies the Next.js static export into the Hono project:
//   out/_next/**   -> public/static/landing/_next/**   (served by Cloudflare as static assets)
//   out/index.html -> src/generated/landing-html.ts    (returned by the worker at "/")
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const out = join(here, '..', 'out')
const root = join(here, '..', '..')
if (!existsSync(join(out, 'index.html'))) throw new Error('Run `next build` first: frontend/out/index.html is missing')

const assets = join(root, 'public', 'static', 'landing')
rmSync(assets, { recursive: true, force: true })
mkdirSync(assets, { recursive: true })
cpSync(join(out, '_next'), join(assets, '_next'), { recursive: true })

const html = readFileSync(join(out, 'index.html'), 'utf8')
const gen = join(root, 'src', 'generated')
mkdirSync(gen, { recursive: true })
writeFileSync(
  join(gen, 'landing-html.ts'),
  `// AUTO-GENERATED by frontend/scripts/export-to-worker.mjs. Do not edit by hand.\nexport const LANDING_HTML = ${JSON.stringify(html)}\n`,
)
console.log(`landing exported: ${(html.length / 1024).toFixed(1)} KB html`)
